// EXP 007 WO-1-01: vendor each plugin's own rules, pinned by commit, into experiments/blueprint-floor/rules/<plugin>.json.
//   node scripts/blueprint-floor-rules.mjs --write --from <dir>   extract from clones at <dir>/<plugin> (each at its pin)
//   node scripts/blueprint-floor-rules.mjs --verify [--from <dir>] re-extract (default: fresh clones at the pins, network)
//                                                                 and require byte-identical files
// CI never needs the network: scripts/blueprint-floor-rules.test.mjs re-checks the committed files' own shas and counts.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { extractPlugin } from '../experiments/blueprint-floor/extract.mjs';

export const RULES_DIR = 'experiments/blueprint-floor/rules';
export const selectionPath = `${RULES_DIR}/selection.json`;
export const selectionDocPath = `${RULES_DIR}/SELECTION.md`;
export const loadSelection = (root = '.') => JSON.parse(readFileSync(join(root, selectionPath), 'utf8'));
export const rulesPath = plugin => `${RULES_DIR}/${plugin}.json`;
export const loadRules = (plugin, root = '.') => JSON.parse(readFileSync(join(root, rulesPath(plugin)), 'utf8'));
export const serialise = record => JSON.stringify(record, null, 2) + '\n';

function gitAt(dir, args) { return execFileSync('git', ['-C', dir, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim(); }

/** A reader over a clone, after proving the clone's HEAD is the pin. */
export function cloneReader(dir, sha) {
  const head = gitAt(dir, ['rev-parse', 'HEAD']);
  if (head !== sha) throw new Error(`${dir} is at ${head}, not the pin ${sha}`);
  if (gitAt(dir, ['status', '--porcelain'])) throw new Error(`${dir} has local changes`);
  return rel => readFileSync(join(dir, rel), 'utf8');
}

export function renderSelectionDoc(selection, records) {
  const lines = ['# EXP 007 rule selection (generated; do not edit)', '', 'Generated by `node scripts/blueprint-floor-rules.mjs --write` from `selection.json` and the extracted rule files. A test re-renders it and fails on any difference.', '',
    `**Inclusion test.** ${selection.inclusionTest}`, '', `**Applies to.** ${selection.contextRule}`, '', `**Class cap.** ${selection.maxClassRule}`, '', `**Granularity.** ${selection.granularity}`, '', `**Text field.** ${selection.textField}`, '', `**Input kind.** ${selection.inputKinds}`, '', `**Regex flags.** ${selection.regexFlags}`, '',
    '| Plugin | Pin | Primary | Secondary (sample) | Excluded |', '|---|---|---:|---:|---:|'];
  for (const p of selection.plugins) {
    const r = records[p.plugin];
    lines.push(`| ${p.plugin} | \`${p.repo}@${p.sha.slice(0, 8)}\` | ${r.counts.primary} | ${r.counts.secondary} | ${r.counts.excluded} |`);
  }
  for (const p of selection.plugins) {
    const r = records[p.plugin];
    lines.push('', `## ${p.plugin}`, '', `Repository \`${p.repo}\` at \`${p.sha}\`, ${r.license}, ${r.copyright}.`, '', `- Items: ${p.primary.items}.`, `- Text field: ${p.primary.textField}.`,
      `- Input kind: ${typeof p.primary.inputKind === 'string' ? p.primary.inputKind : Object.entries(p.primary.inputKind).map(([k, v]) => `${k} → ${v}`).join(', ')} (${p.primary.inputKindEvidence}).`);
    if (p.primary.comparisonOnly) lines.push(`- Comparison only: ${p.primary.comparisonOnly}.`);
    if (p.secondary) lines.push(`- Secondary stratum: ${p.secondary.items}; a seeded sample of ${p.secondary.sample.size} (seed ${p.secondary.sample.seed}) from ${r.secondaryPopulation.size}. ${p.secondary.sample.method}. ${p.secondary.note}`);
    if (p.plugin === 'abide') {
      const nul = r.rules.filter(x => x.withheld.when === null).length;
      lines.push(`- Rules with when = null, assigned diff: ${nul} of ${r.counts.primary} (${Math.round(nul / r.counts.primary * 1000) / 10}%).`);
    }
    for (const c of p.contexts ?? []) lines.push(`- Applies to${c.match ? ` (${c.match}${c.when ? `, when ${c.when}` : ''})` : c.scope ? ' (a rule with a scope)' : ' (a rule with files)'}: "${c.context}" (${c.cite}).`);
    for (const c of (p.contexts ?? []).filter(x => x.maxClass)) lines.push(`- Class cap (${c.match}): at most ${c.maxClass}, because the ${c.maxClassReason}.`);
    if (!(p.contexts ?? []).length) lines.push('- Applies to: no context line (no rule of this plugin is in the census).');
    const none = r.rules.filter(x => x.context === null).length;
    if (none) lines.push(`- Rules with no context line: ${none} (${r.rules.filter(x => x.context === null).map(x => x.ruleId.split('/').pop()).join(', ')}): the source names no match target for them.`);
    lines.push(`- Primary rules: ${r.counts.primary}.`);
    if (r.excluded.length) {
      lines.push('', 'Excluded:', '');
      for (const e of r.excluded) lines.push(`- \`${e.id}\` (${e.sourcePath}:${e.line}): ${e.reason}`);
    }
    for (const s of p.excludedSources ?? []) lines.push(`- Source not extracted: ${s.source}: ${s.reason}.`);
    if (r.counts.primary === 0) lines.push('', `No item of ${p.plugin} passes the inclusion test, so its primary stratum is empty; it is listed, and it has no share in the median.`);
  }
  lines.push('', '## Out of scope', '');
  for (const o of selection.outOfScope) lines.push(`- ${o.plugin}${o.repo ? ` (\`${o.repo}\`)` : ''}: ${o.reason}.`);
  return lines.join('\n') + '\n';
}

function writeAll(recordsBy) {
  const selection = loadSelection();
  for (const [plugin, record] of Object.entries(recordsBy)) writeFileSync(rulesPath(plugin), serialise(record));
  writeFileSync(selectionDocPath, renderSelectionDoc(selection, recordsBy));
}

export function extractAll(readerFor) {
  const selection = loadSelection();
  return Object.fromEntries(selection.plugins.map(p => [p.plugin, extractPlugin(p, readerFor(p))]));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const fromAt = args.indexOf('--from');
  const from = fromAt >= 0 ? args[fromAt + 1] : null;
  const selection = loadSelection();
  if (args[0] === '--write') {
    if (!from) { console.error('--write needs --from <dir>'); process.exit(2); }
    const records = extractAll(p => cloneReader(join(from, p.plugin), p.sha));
    writeAll(records);
    for (const [p, r] of Object.entries(records)) console.log(`${p}: primary ${r.counts.primary}, secondary ${r.counts.secondary}, excluded ${r.counts.excluded}`);
  } else if (args[0] === '--verify') {
    let root = from, temp = null;
    if (!root) {
      temp = root = mkdtempSync(join(tmpdir(), 'blueprint-floor-verify-'));
      for (const p of selection.plugins) {
        const dir = join(root, p.plugin);
        execFileSync('git', ['clone', '-q', `https://github.com/${p.repo}.git`, dir], { stdio: 'inherit' });
        execFileSync('git', ['-C', dir, 'checkout', '-q', p.sha], { stdio: 'inherit' });
      }
    }
    try {
      const records = extractAll(p => cloneReader(join(root, p.plugin), p.sha));
      let bad = 0;
      for (const [p, r] of Object.entries(records)) {
        const same = existsSync(rulesPath(p)) && readFileSync(rulesPath(p), 'utf8') === serialise(r);
        console.log(`${same ? 'SAME' : 'DIFFERS'} ${rulesPath(p)}`);
        if (!same) bad++;
      }
      const doc = readFileSync(selectionDocPath, 'utf8') === renderSelectionDoc(selection, records);
      console.log(`${doc ? 'SAME' : 'DIFFERS'} ${selectionDocPath}`);
      if (bad || !doc) process.exit(1);
      console.log('PASS: every vendored rule file re-extracts byte for byte at its pin.');
    } finally { if (temp) rmSync(temp, { recursive: true, force: true }); }
  } else {
    console.error('usage: node scripts/blueprint-floor-rules.mjs --write --from <dir> | --verify [--from <dir>]');
    process.exit(2);
  }
}
