// The provider brief as Markdown, for the seed deck (vp-grow-odin-r-d bundle-4, WO-VG-05). It renders the same claims
// as site/provider-brief/ (site/data/provider-brief.json through scripts/lab-pages.mjs), so the deck can say no more
// than the published page: every number is a link to its experiment record on the public site, with the JSON pointer
// it was read from as the fragment. EXP 018 (verdict incomplete) and EXP 019 (not yet run) appear only in the list
// of what is not a result.
//
//   node scripts/provider-brief-export.mjs > deck-evidence.md
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, realpathSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { checkPage, recordProblem } from './number-provenance.mjs';
import { PAGES, briefProblems, renderLabPages, renderProviderBrief, siteReader } from './lab-pages.mjs';

export const BASE = 'https://odin-labs-ai.github.io/odin-rnd/';

const decode = text => text.replace(/&nbsp;/g, ' ').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&amp;/g, '&');

/** Rendered brief HTML (relative links from provider-brief/) to Markdown with absolute links. */
export function toMarkdown(html, base = BASE) {
  const abs = href => (/^[a-z]+:/i.test(href) ? href : base + href.replace(/^\.\.\//, ''));
  return decode(html
    .replace(/<a class="lab-num" href="[^"]*" data-source="([^"]*)"[^>]*>([^<]*)<\/a>/g, (_, source, value) => `[${value}](${base}${source})`)
    .replace(/<a href="([^"]*)"[^>]*>([^<]*)<\/a>/g, (_, href, text) => `[${text}](${abs(href)})`)
    .replace(/<a href="([^"]*)"[^>]*><code>([^<]*)<\/code><\/a>/g, (_, href, text) => `[\`${text}\`](${abs(href)})`)
    .replace(/<code>([^<]*)<\/code>/g, '`$1`')
    .replace(/<time[^>]*>([^<]*)<\/time>/g, '$1')
    .replace(/<strong>([^<]*)<\/strong>/g, '**$1**')
    .replace(/<cite[^>]*>([^<]*)<\/cite>/g, '*$1*')
    .replace(/<h2[^>]*>([^<]*)<\/h2>/g, '\n### $1\n\n')
    .replace(/<\/p><p class="lab-source">/g, '\n  ')
    .replace(/<li[^>]*>/g, '- ')
    .replace(/<\/li>/g, '\n')
    .replace(/<\/p>/g, '\n\n')
    // Any tag left is dropped, then any stray angle bracket; entities are decoded after that, and an angle bracket
    // the decoding brings back is escaped again below, so no markup reaches the Markdown.
    .replace(/<[^>]*>/g, '').replace(/[<>]/g, ''))
    .replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/[ \t]+\n/g, '\n').replace(/\n{3,}/g, '\n\n').trim() + '\n';
}

/** The deck section: a provenance header, then the brief's measured claims and its not-a-result list. */
export function deckMarkdown({ root = 'site', read = siteReader(root), revision = 'unknown', base = BASE } = {}) {
  const problems = briefProblems(read(PAGES['provider-brief'].config));
  // The same gate the build runs on the page: every number sourced from a bound experiment record, shown exactly.
  const page = renderLabPages({ root, read })['provider-brief'];
  const readData = path => (existsSync(join(root, path)) ? readFileSync(join(root, path), 'utf8') : null);
  problems.push(...checkPage('provider-brief/index.html', page, { readData, recordProblem: (path, raw) => recordProblem(path, raw, join(root, '..')) }));
  if (problems.length) throw new Error(problems.join('\n'));
  return [
    '## Evidence: what the Odin R&D lab has measured',
    '',
    `> Generated by \`node scripts/provider-brief-export.mjs\` from odin-rnd at \`${revision}\`, from the same records as ${base}provider-brief/ . Every number links to the experiment record it was read from (the link fragment is the JSON pointer). Do not edit numbers by hand; regenerate.`,
    '',
    toMarkdown(renderProviderBrief(read), base),
  ].join('\n');
}

